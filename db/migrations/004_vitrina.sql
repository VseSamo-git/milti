-- Витрина Димы: ровно семь листов из его задания, по-русски.
--
-- ЗАЧЕМ ОТДЕЛЬНАЯ СХЕМА. NocoDB показывает всё, что видит в схеме. Если
-- смотреть в kosmos, Дима видит 11 таблиц, включая служебные observations,
-- runs и verdicts — базу разработчика вместо рабочего инструмента.
-- Схема «vitrina» содержит СЕМЬ вью и больше ничего, поэтому NocoDB
-- показывает ровно семь листов.
--
-- Порядковый номер в имени («1. БЦ Москвы») — не украшение: NocoDB
-- сортирует таблицы по алфавиту, и без номеров списки Димы встали бы
-- в случайном порядке.
--
-- Вью, а не таблицы: копии нет, данные всегда живые. Обогащение доливает
-- площади — они появляются здесь сами.

CREATE SCHEMA IF NOT EXISTS vitrina;

-- ---------------------------------------------------------------------
-- 1. БЦ Москвы от 10 000 м²
--
-- Источник: перечень 700-ПП (объекты, где город установил офисное
-- использование) + площадь из ЕГРН. Название БЦ пока пустое почти везде:
-- ни перечень, ни ЕГРН названий не содержат — нужен 2ГИС. Пустая ячейка
-- честнее выдуманной.
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."1 БЦ Москвы";
CREATE VIEW vitrina."1 БЦ Москвы" AS
SELECT
    o.title                              AS "Название БЦ",
    o.address                            AS "Адрес",
    round(o.area_sqm)::int               AS "Общая площадь, м²",
    o.floors                             AS "Этажей",
    o.built_year                         AS "Год постройки",
    CASE o.status
        WHEN 'вычтен' THEN 'наша точка уже есть'
        ELSE 'в работе'
    END                                  AS "Статус",
    o.first_seen_at::date                AS "Добавлен",
    o.area_source                        AS "Источник площади",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.annex = 1
  AND o.area_sqm >= 10000
ORDER BY o.area_sqm DESC;

-- ---------------------------------------------------------------------
-- 2. Офисные здания от 10 000 м²
--
-- Дима просит отдельно «здания, которые по картам не определяются как БЦ,
-- но функционируют как БЦ». Признак попадания в перечень 700-ПП — ровно
-- это: Госинспекция установила, что >20% площади занято офисами.
--
-- ЧЕСТНО: отделить их от БЦ пока нечем. И то и другое — здания из
-- перечня, а названия, по которому видно «это БЦ Кутузовский», у нас нет.
-- Разделение появится с 2ГИС. Пока лист показывает те же здания с
-- пометкой, чтобы Дима видел объём, а не пустоту.
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."2 Офисные здания";
CREATE VIEW vitrina."2 Офисные здания" AS
SELECT
    o.address                            AS "Адрес",
    round(o.area_sqm)::int               AS "Общая площадь, м²",
    o.floors                             AS "Этажей",
    o.built_year                         AS "Год постройки",
    'офисное использование установлено городом (перечень 700-ПП)'
                                         AS "Основание",
    o.first_seen_at::date                AS "Добавлен",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.annex = 1
  AND o.area_sqm >= 10000
  AND o.title IS NULL
ORDER BY o.area_sqm DESC;

-- ---------------------------------------------------------------------
-- 3. Офисы больших компаний
--
-- Нужны название компании и число сотрудников — этого нет ни в перечне,
-- ни в ЕГРН, ни в OSM. Единственный источник — 2ГИС. Лист создан пустым
-- намеренно: Дима должен видеть, что пункт не забыт, а ждёт ключа.
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."3 Офисы компаний";
CREATE VIEW vitrina."3 Офисы компаний" AS
SELECT
    o.title                              AS "Название компании",
    o.address                            AS "Адрес",
    round(o.area_sqm)::int               AS "Общая площадь офиса, м²",
    o.org_count                          AS "Организаций в здании",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.org_count IS NOT NULL
ORDER BY o.org_count DESC;

-- ---------------------------------------------------------------------
-- 4. НИИ
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."4 НИИ";
CREATE VIEW vitrina."4 НИИ" AS
SELECT
    p.name                                                   AS "Название НИИ",
    coalesce(p.address, o.address)                           AS "Адрес",
    round(o.area_sqm)::int                                   AS "Общая площадь, м²",
    p.lat || ', ' || p.lon                                   AS "Координаты",
    CASE p.status WHEN 'активна' THEN 'действует' ELSE p.status END AS "Статус",
    p.first_seen_at::date                                    AS "Добавлен"
FROM kosmos.places p
LEFT JOIN kosmos.objects o ON o.id = p.object_id
WHERE p.kind = 'нии'
ORDER BY p.name;

-- ---------------------------------------------------------------------
-- 5. ВУЗы
--
-- Колледжи включены сознательно: Дима просил ВУЗы, но колледж с двумя
-- тысячами студентов даёт островку тот же трафик. Тип вынесен в колонку,
-- чтобы Дима мог отфильтровать, если они ему не нужны.
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."5 ВУЗы";
CREATE VIEW vitrina."5 ВУЗы" AS
SELECT
    p.name                                                   AS "Название",
    CASE p.kind WHEN 'вуз' THEN 'ВУЗ' ELSE 'колледж' END     AS "Тип",
    coalesce(p.address, o.address)                           AS "Адрес",
    round(o.area_sqm)::int                                   AS "Общая площадь, м²",
    p.students                                               AS "Студентов по адресу",
    p.lat || ', ' || p.lon                                   AS "Координаты",
    p.first_seen_at::date                                    AS "Добавлен"
FROM kosmos.places p
LEFT JOIN kosmos.objects o ON o.id = p.object_id
WHERE p.kind IN ('вуз', 'колледж')
ORDER BY p.kind, p.name;

-- ---------------------------------------------------------------------
-- 6. ТЦ с продуктовым супермаркетом
--
-- Седьмой список Димы из второй версии письма. Нужна связка «супермаркет
-- внутри здания -> само здание»: Пятёрочка на первом этаже ТЦ и сам ТЦ —
-- разные объекты, и путать их нельзя. Связка в работе.
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."6 ТЦ с супермаркетом";
CREATE VIEW vitrina."6 ТЦ с супермаркетом" AS
SELECT
    o.title                              AS "Название ТЦ",
    o.address                            AS "Адрес",
    p.name                               AS "Продуктовый супермаркет",
    round(o.area_sqm)::int               AS "Общая площадь, м²",
    p.lat || ', ' || p.lon               AS "Координаты"
FROM kosmos.places p
JOIN kosmos.objects o ON o.id = p.object_id
WHERE p.kind = 'супермаркет'
ORDER BY o.area_sqm DESC NULLS LAST;

-- ---------------------------------------------------------------------
-- 7. Конкуренты
--
-- Все 11 сетей из задания. Адреса — с официальных сайтов сетей, поэтому
-- точные. «Кандидат на закрытие» означает: точка пропала с сайта сети,
-- но это ещё не доказательство закрытия — надо проверить.
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."7 Конкуренты";
CREATE VIEW vitrina."7 Конкуренты" AS
SELECT
    p.chain                                                  AS "Сеть",
    coalesce(p.address, nullif(trim(coalesce(p.street, '') || ' ' || coalesce(p.house, '')), ''))
                                                             AS "Адрес",
    CASE p.status
        WHEN 'активна'             THEN 'работает'
        WHEN 'кандидат_на_закрытие' THEN 'возможно закрылась — проверить'
        ELSE p.status
    END                                                      AS "Статус",
    p.first_seen_at::date                                    AS "Впервые увидели",
    p.last_seen_at::date                                     AS "Последний раз видели",
    p.source                                                 AS "Источник"
FROM kosmos.places p
WHERE p.kind = 'конкурент'
ORDER BY p.chain, p.address;
