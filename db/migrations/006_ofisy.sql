-- Лист 3: офисы больших компаний.
--
-- ЧТО ПРОСИЛ ДИМА: название компании, адрес, площадь офиса, количество
-- сотрудников. Отдаём первые три. Четвёртого нет ни в одном открытом
-- источнике, и выдумывать его нельзя.
--
-- ВМЕСТО СОТРУДНИКОВ — «организаций в здании». Это не то же самое, но
-- честный сигнал офисной плотности: пять юрлиц в доме на 30 000 м² и
-- одно — разные истории. Колонка названа так, как есть, чтобы её не
-- приняли за численность персонала.
--
-- ПЛОЩАДЬ — здания, а не офиса. Разделить нечем: ЕГРН даёт площадь дома,
-- кто какой этаж занимает — не знает никто, кроме собственника. Название
-- колонки об этом говорит прямо.
--
-- Порог 5000 м²: Диме нужны БОЛЬШИЕ компании. Юрист в доме на 400 м² —
-- не его история, а мусор в списке.

DROP VIEW IF EXISTS vitrina."3 Офисы компаний";
CREATE VIEW vitrina."3 Офисы компаний" AS
SELECT
    f.name                               AS "Название компании",
    o.address                            AS "Адрес",
    o.title                              AS "Здание",
    round(o.area_sqm)::int               AS "Площадь здания, м²",
    o.org_count                          AS "Организаций в здании",
    o.floors                             AS "Этажей",
    CASE
        WHEN f.distance_m <= 15 THEN 'привязка точная'
        WHEN f.distance_m <= 30 THEN 'привязка скорее верная'
        ELSE 'привязку проверить'
    END                                  AS "Достоверность",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.offices f
JOIN kosmos.objects o ON o.id = f.object_id
WHERE o.area_sqm >= 5000
ORDER BY o.area_sqm DESC;
