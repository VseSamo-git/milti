-- Лист 1 «БЦ Москвы»: перестройка с фильтра OSM-меток на официальный реестр.
--
-- ПОЧЕМУ. Прежде лист = annex=1 ∧ area≥10k ∧ object_type='бц'. Метка 'бц'
-- ставится только по совпадению имени в OSM в радиусе 60 м — это слишком
-- строго. Из 656 объектов реестра ≥10k так распознавались лишь 260, а 290
-- оставались 'неизвестен' (среди них живые БЦ), 106 — распознанные ТЦ.
-- Дима сверился с arendator (800+ БЦ Москва+область) — мы недобирали.
--
-- НОВАЯ ЛОГИКА: сам перечень 700-ПП уже говорит «это административно-деловой
-- объект». Поэтому показываем ВЕСЬ реестр ≥10k, вычтя ретейл, и метим
-- достоверность профиля:
--   • object_type='бц'            → «БЦ подтверждён» (260, готов к работе);
--   • 'неизвестен', имя не ретейл → «проверить профиль» (~242, живые БЦ + шум).
-- Вычитаем: object_type='тц' (есть продуктовый внутри, это лист 6) и объекты
-- с явно торговым/непрофильным именем (Авиапарк, Мореон, ТПУ и т.п.).
--
-- «Плаза»/«пассаж» НЕ вычитаем: настоящих БЦ с такими именами больше, чем
-- моллов (Омега-Плаза, Ньютон Плаза, Газойл Плаза), — отсечка спрятала бы БЦ.
-- Метка 'бц' здесь неприкосновенна: ретейл-регекс применяется только к
-- 'неизвестен', поэтому БЦ со словом в имени («ТДЦ Гульден») остаётся.
--
-- Кадастр одного объекта ≠ БЦ целиком (башни комплекса разбиты на кадастры),
-- поэтому порог 10 000 м² на объект — это уже крупный центр.

DROP VIEW IF EXISTS vitrina."1 БЦ Москвы";
CREATE VIEW vitrina."1 БЦ Москвы" AS
SELECT o.title AS "Название БЦ",
    vitrina.addr_short(o.address) AS "Адрес",
    round(o.area_sqm)::integer AS "Общая площадь, м²",
    o.floors AS "Этажей",
    o.built_year AS "Год постройки",
    CASE
        WHEN o.object_type = 'бц' THEN 'БЦ подтверждён'
        ELSE 'проверить профиль'
    END AS "Профиль",
    CASE
        WHEN o.title_distance_m <= 15 THEN 'название точное'
        WHEN o.title_distance_m <= 30 THEN 'название скорее верное'
        WHEN o.title IS NULL THEN 'название неизвестно'
        ELSE 'название проверить'
    END AS "Достоверность названия",
    CASE o.status
        WHEN 'вычтен' THEN 'наша точка уже есть'
        ELSE 'в работе'
    END AS "Статус",
    o.cadastral_no AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.annex = 1
  AND o.area_sqm >= 10000
  AND (
    o.object_type = 'бц'
    OR (
      o.object_type = 'неизвестен'
      AND (o.title IS NULL OR o.title !~* '(торгов|ТРЦ|ТРК|\mТЦ\M|молл|\mmall\M|аутлет|outlet|универмаг|рынок|гипермаркет|ярмарк|вернисаж|shopping|ритейл|автосалон|моторс|мебель|дилерск|аквапарк|пересадочн|вокзал)')
    )
  )
ORDER BY (o.object_type <> 'бц'), o.area_sqm DESC;
