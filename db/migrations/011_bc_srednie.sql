-- Новый лист «8 БЦ средние 5–10 тыс. м²»: БЦ, что не дотянули до порога 10 000.
--
-- ПОЧЕМУ ОТДЕЛЬНЫМ ЛИСТОМ. Лист 1 остаётся как в ТЗ — крупные БЦ от 10 000 м²
-- (260 шт.). Но в базе размечено 1372 БЦ, и 189 из них лежат в 5 000–10 000 —
-- это настоящие БЦ («Каланчёвский», «Селезнёвская 11», башни комплексов),
-- их прятал порог. Дима ждал ~400 (260+189=449), и загугленные каталоги
-- это подтвердили (roomfi 928, arendator класс B 680). Не смешиваем со
-- списком 1: гиганты и средние — разные по значимости, отдельный лист чище.
--
-- Кадастр одного объекта ≠ БЦ целиком (башни комплекса разбиты на кадастры),
-- поэтому 5 000 м² на объект — уже заметный центр, а не киоск.

-- Точка в имени таблицы NocoDB запрещена, поэтому имя без «тыс.м²».
DROP VIEW IF EXISTS vitrina."8 БЦ средние 5-10 тыс.м²";
DROP VIEW IF EXISTS vitrina."8 БЦ средние 5-10к";
CREATE VIEW vitrina."8 БЦ средние 5-10к" AS
SELECT o.title AS "Название БЦ",
    vitrina.addr_short(o.address) AS "Адрес",
    round(o.area_sqm)::integer AS "Общая площадь, м²",
    o.floors AS "Этажей",
    o.built_year AS "Год постройки",
    CASE
        WHEN o.title_distance_m <= 15 THEN 'название точное'
        WHEN o.title_distance_m <= 30 THEN 'название скорее верное'
        ELSE 'название проверить'
    END AS "Достоверность названия",
    CASE o.status
        WHEN 'вычтен' THEN 'наша точка уже есть'
        ELSE 'в работе'
    END AS "Статус",
    o.cadastral_no AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.annex = 1 AND o.area_sqm >= 5000 AND o.area_sqm < 10000 AND o.object_type = 'бц'
ORDER BY o.area_sqm DESC;
