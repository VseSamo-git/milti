-- 025 — ОТВЕТЫ ДИМЫ от 18.08.2026. Три удаления и снятый радиус.
--
-- 1. «точки не мешают друг другу» — радиуса каннибализации НЕТ. Предложение
--    про 150 метров отклонено. Вычитание точек МИЛТИ остаётся ровно тем, чем
--    было: совпадение здания (адрес + допуск 30 м на разброс координат одной
--    и той же точки), а не зона влияния. Кода здесь нет — записано, чтобы
--    никто не «улучшил» это позже, приняв допуск матчинга за радиус влияния.
--
-- 2. «колледжи нахуй удаляй» — 284 колледжа уходят из «Базы».
-- 3. «подмосковье нахуй удаляй» — 54 объекта с «Московская обл» в адресе.
-- 4. «БЦ 5-10тыс кв м — нахуй удаляй» — лист витрины удаляется целиком.
--
-- ПОЧЕМУ СТАТУС, А НЕ DELETE. Инвариант §12: машина не удаляет. Дима решение
-- принял, но строки остаются в kosmos.places / kosmos.objects со статусом
-- вычитания — вью их не показывает, а передумать стоит одного UPDATE обратно.
-- Вью «База» не переписываем: она уже фильтрует p.status = 'активна', и
-- вычитание колледжей ложится в тот же механизм, что вычитание наших точек.
--
-- ВНИМАНИЕ по пункту 3: Новая Москва (Коммунарка, Калужское ш., Троицк) и
-- Зеленоград формально Москва и под фильтр «Московская обл» НЕ попадают, но
-- лежат за МКАД и вне всех 14 секторов — это ~57 объектов. Вынесено Диме
-- отдельным вопросом, здесь не трогаем.
--
-- 5. «кто должен подтверждать объекты» → «я». Схема подтверждена без
--    изменений: объект из реестра сразу в Базе, ОК нужен внешним каталогам
--    и очереди «На проверку». Кода нет.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Подмосковье — свой статус вычитания у зданий
-- ---------------------------------------------------------------------------
ALTER TABLE kosmos.objects DROP CONSTRAINT IF EXISTS valid_status;
ALTER TABLE kosmos.objects ADD CONSTRAINT valid_status CHECK (status IN (
  'активен',
  'не_найден_в_последнем_обходе',
  'вычтен_наша_точка',
  'вычтен_закрытая_точка',
  'вычтен_подмосковье',
  'дубль_в_базе'
));

UPDATE kosmos.objects
   SET status = 'вычтен_подмосковье'
 WHERE status = 'активен' AND address ILIKE '%Московская обл%';   -- 54 строки

-- ---------------------------------------------------------------------------
-- 2. Колледжи — свой статус вычитания у мест
-- ---------------------------------------------------------------------------
ALTER TABLE kosmos.places DROP CONSTRAINT IF EXISTS valid_place_status;
ALTER TABLE kosmos.places ADD CONSTRAINT valid_place_status CHECK (status IN (
  'активна',
  'кандидат_на_закрытие',
  'вычтен_наша_точка',
  'вычтен_закрытая_точка',
  'вычтен_решением_димы',
  'дубль_в_базе'
));

UPDATE kosmos.places
   SET status = 'вычтен_решением_димы'
 WHERE kind = 'колледж' AND status = 'активна';                   -- 284 строки

-- ---------------------------------------------------------------------------
-- 3. Лист «БЦ средние 5-10к» — удалён вместе с определением
-- ---------------------------------------------------------------------------
DROP VIEW IF EXISTS vitrina."БЦ средние 5-10к";

COMMIT;
