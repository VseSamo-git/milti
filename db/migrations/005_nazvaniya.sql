-- Названия зданий в витрине + разделение БЦ и офисных зданий.
--
-- КАК РАЗВЕДЕНЫ БЦ И ОФИСНЫЕ ЗДАНИЯ. Формулировка Димы: «здания, которые
-- по картам не определяются как БЦ, но при этом функционируют как БЦ».
-- Значит признак ровно один — опознан ли объект картами:
--
--   название нашлось в OSM, профиль деловой  -> лист 1, БЦ
--   названия на картах нет, но объект в перечне 700-ПП
--     (город установил офисное использование) -> лист 2, офисное здание
--
-- Второй случай буквально и есть «функционирует как БЦ, но картами
-- не опознан». Раньше оба листа показывали одно и то же — теперь нет.
--
-- ДОСТОВЕРНОСТЬ НАЗВАНИЯ. Привязка идёт по расстоянию между центроидом
-- здания в ЕГРН и центроидом в OSM. Проверено на живых данных: до 15 м
-- легло 1032 здания, 15-30 м — 263, дальше 30 м — 997. Последние нельзя
-- показывать молча как факт: у крупного здания смещение 50 м нормально,
-- у мелкого — это уже соседний дом. Поэтому расстояние превращается
-- в честную пометку, и Дима видит, чему верить.

DROP VIEW IF EXISTS vitrina."1 БЦ Москвы";
CREATE VIEW vitrina."1 БЦ Москвы" AS
SELECT
    o.title                              AS "Название БЦ",
    o.address                            AS "Адрес",
    round(o.area_sqm)::int               AS "Общая площадь, м²",
    o.floors                             AS "Этажей",
    o.built_year                         AS "Год постройки",
    CASE
        WHEN o.title_distance_m <= 15 THEN 'название точное'
        WHEN o.title_distance_m <= 30 THEN 'название скорее верное'
        ELSE 'название проверить'
    END                                  AS "Достоверность названия",
    CASE o.status WHEN 'вычтен' THEN 'наша точка уже есть' ELSE 'в работе' END
                                         AS "Статус",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.annex = 1
  AND o.area_sqm >= 10000
  AND o.object_type = 'бц'
ORDER BY o.area_sqm DESC;

-- Лист 2: в перечне есть, на картах как БЦ не опознан.
DROP VIEW IF EXISTS vitrina."2 Офисные здания";
CREATE VIEW vitrina."2 Офисные здания" AS
SELECT
    o.address                            AS "Адрес",
    round(o.area_sqm)::int               AS "Общая площадь, м²",
    o.floors                             AS "Этажей",
    o.built_year                         AS "Год постройки",
    'офисное использование установлено городом (перечень 700-ПП), '
      || 'на картах как БЦ не значится'   AS "Основание",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.annex = 1
  AND o.area_sqm >= 10000
  AND o.title IS NULL
ORDER BY o.area_sqm DESC;

-- Лист 6: торговые центры. Супермаркет внутри — следующий шаг,
-- пока показываем сами ТЦ, чтобы список не стоял пустым.
DROP VIEW IF EXISTS vitrina."6 ТЦ с супермаркетом";
CREATE VIEW vitrina."6 ТЦ с супермаркетом" AS
SELECT
    o.title                              AS "Название ТЦ",
    o.address                            AS "Адрес",
    round(o.area_sqm)::int               AS "Общая площадь, м²",
    o.floors                             AS "Этажей",
    CASE
        WHEN o.title_distance_m <= 15 THEN 'название точное'
        WHEN o.title_distance_m <= 30 THEN 'название скорее верное'
        ELSE 'название проверить'
    END                                  AS "Достоверность названия",
    'супермаркет внутри — уточняется'    AS "Продуктовый супермаркет",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.object_type = 'тц'
ORDER BY o.area_sqm DESC NULLS LAST;
