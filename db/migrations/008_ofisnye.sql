-- Лист 2 «Офисные здания»: убрать то, что офисным зданием не является.
--
-- ЧТО БЫЛО НЕ ТАК. Признак «в перечне 700-ПП + нет названия на картах»
-- слишком широк. Перечень ведётся по ст. 378.2 НК, а она охватывает
-- НЕ ТОЛЬКО офисы: туда же входят торговые центры, общепит и бытовое
-- обслуживание. Поэтому в лист затекали:
--   - 7 зданий с супермаркетом внутри — это ТЦ, их место в листе 6;
--   - склады и рынки: 162 630 м² при трёх этажах в Южнопортовом,
--     72 874 м² при четырёх в Солнцеве.
--
-- ПРИЗНАК, КОТОРЫЙ ИХ РАЗДЕЛЯЕТ — площадь на этаж. У офисной башни она
-- скромная, у склада огромная, и это геометрия, а не эвристика:
--   Пресненская башня  173 960 / 80 =  2 175 м² на этаж — офис
--   Южнопортовый       162 630 /  3 = 54 210 м² на этаж — склад
--   Солнцево            72 874 /  4 = 18 218 м² на этаж — ТЦ
-- Порог 8000 м² на этаж: выше него офисных зданий не бывает, ниже
-- попадают и башни, и широкие сталинки.
--
-- Этажность бывает неизвестна — такие НЕ выбрасываем: отсутствие данных
-- не доказывает, что здание плохое. Они помечаются «этажность неизвестна»,
-- и Дима решает сам.

DROP VIEW IF EXISTS vitrina."2 Офисные здания";
CREATE VIEW vitrina."2 Офисные здания" AS
SELECT
    o.address                            AS "Адрес",
    round(o.area_sqm)::int               AS "Общая площадь, м²",
    o.floors                             AS "Этажей",
    CASE
        WHEN o.floors IS NULL OR o.floors = 0 THEN 'этажность неизвестна'
        WHEN o.area_sqm / o.floors <= 3000    THEN 'похоже на офисное'
        ELSE 'проверить: широкое здание'
    END                                  AS "Профиль",
    o.org_count                          AS "Организаций в здании",
    o.built_year                         AS "Год постройки",
    o.cadastral_no                       AS "Кадастровый номер"
FROM kosmos.objects o
WHERE o.annex = 1
  AND o.area_sqm >= 10000
  AND o.title IS NULL
  -- Супермаркет внутри — это торговый центр, а не офисное здание.
  AND o.supermarkets IS NULL
  -- Склады и рынки: столько площади на этаж офисы не занимают.
  AND (o.floors IS NULL OR o.floors = 0 OR o.area_sqm / o.floors < 8000)
ORDER BY o.area_sqm DESC;
