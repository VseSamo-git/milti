/**
 * Точка внутри полигона — луч вправо, считаем пересечения (ray casting).
 * Работает в градусах: на масштабе Москвы искажение проекции меньше,
 * чем неточность самой границы, нарисованной со слов.
 *
 * @param {number} lat
 * @param {number} lon
 * @param {[number, number][]} polygon
 */
export function inPolygon(lat, lon, polygon) {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [latI, lonI] = polygon[i];
    const [latJ, lonJ] = polygon[j];
    const straddles = latI > lat !== latJ > lat;
    if (!straddles) continue;
    const lonAtLat = lonI + ((lat - latI) * (lonJ - lonI)) / (latJ - latI);
    if (lon < lonAtLat) inside = !inside;
  }
  return inside;
}

/**
 * В каком секторе точка. NULL — законный ответ: сектора Димы покрывают
 * не всю Москву, объект вне их — не ошибка, а «пока не в нарезке».
 *
 * @returns {Sector | null}
 */
export function sectorOf(lat, lon) {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
  for (const s of SECTORS) if (inPolygon(lat, lon, s.polygon)) return s;
  return null;
}
