/**
 * Нормализованные ключи адреса и названия — общий язык всех сверок.
 *
 * ЗАЧЕМ. Один физический дом приезжает к нам из четырёх источников и в каждом
 * записан по-своему: «ул. Бутырская, д. 77», «улица Бутырская, дом 77»,
 * «Бутырская ул., 77». Сравнение строк даёт ноль совпадений, сравнение
 * координат промахивается на крупных комплексах (центроиды корпусов расходятся
 * на сотню метров). Работает третий признак — нормализованный адрес.
 *
 * ПРИНЦИП КЛЮЧА. Выкидываем всё, что источник волен писать как угодно (тип
 * улицы, слово «дом», регион, разделители), оставляем два множества: слова
 * улицы и числа дома/корпуса. Оба сортируем — тогда «Бутырская ул. 77» и
 * «ул. Бутырская д.77» дают один ключ, а «Бутырская 77» и «Бутырская 78» —
 * разные. Порядок слов источник тоже волен менять, поэтому сортировка.
 *
 * ПОЧЕМУ ТОКЕНЫ, А НЕ РЕГЭКСП СО \b. Первая редакция резала мусорные слова
 * через `\b(улица|дом|стр)\b` — и молча не работала: в JS `\b` определён по
 * [A-Za-z0-9_], между пробелом и кириллической буквой границы слова НЕТ,
 * поэтому ни одно правило не срабатывало и в ключ уезжали «дом», «переулок»,
 * «москва». Сверка по адресу держалась на честном слове. Теперь строка режется
 * на токены, а стоп-слова отсеиваются точным сравнением — с любым алфавитом.
 *
 * Ключ намеренно строгий: лучше не склеить два одинаковых дома (человек
 * увидит подсказку и решит), чем склеить два разных и потерять лид.
 */

// Гео-шум: регион, тип улицы, слово «дом». Всё, что источник пишет по вкусу.
const ADDR_STOP = new Set([
  'российская', 'федерация', 'россия', 'город', 'москва', 'московская', 'область',
  'обл', 'поселение', 'деревня', 'село', 'посёлок', 'поселок', 'пгт',
  'муниципальный', 'округ', 'район',
  'улица', 'ул', 'проспект', 'проезд', 'переулок', 'пер', 'шоссе',
  'бульвар', 'бул', 'набережная', 'наб', 'площадь', 'пл', 'аллея',
  'линия', 'тупик', 'квартал',
  'дом', 'корпус', 'корп', 'кор', 'строение', 'стр', 'владение', 'вл',
  'литера', 'лит', 'земельный', 'участок',
]);

// Родовые слова названия: есть у половины базы, объекты не различают.
const NAME_STOP = new Set([
  'бизнес', 'центр', 'бц', 'деловой', 'дц', 'многофункциональный', 'комплекс',
  'мфк', 'торговый', 'торгово', 'развлекательный', 'трц', 'трк', 'тц',
  'офисный', 'офисное', 'здание', 'корпус', 'строение', 'стр',
]);

// «19с2» / «1к3» — буква-разделитель между числами это корпус/строение,
// а не литера дома. Раскрываем в «19 2». Одиночную литеру («27А») не трогаем:
// там буква — часть номера дома и различает соседние здания.
const expandCorps = (s) => s.replace(/(\d)\s*[кслв]\s*(\d)/g, '$1 $2');

const tokenize = (s) => s.toLowerCase().replace(/ё/g, 'е').split(/[^0-9a-zа-я]+/).filter(Boolean);

/** Адресный ключ: слова улицы + числа дома. null, если адреса по сути нет. */
export function addrKey(s) {
  if (!s) return null;
  const tokens = tokenize(expandCorps(String(s)));
  const words = [], nums = [];
  for (const t of tokens) {
    if (/\d/.test(t)) { nums.push(t); continue; }
    if (t.length <= 2 || ADDR_STOP.has(t)) continue;   // «д.», «г.», «ул»
    words.push(t);
  }
  if (!words.length || !nums.length) return null;
  return words.sort().join(' ') + '|' + nums.sort().join(' ');
}

/**
 * Ключ названия: «БЦ "Оружейный"», «Бизнес-центр Оружейный» и «оружейный» —
 * одно. Родовые слова выкидываем: склеивать по ним нельзя.
 */
export function nameKey(s) {
  if (!s || s === '(без названия)') return null;
  const tokens = tokenize(String(s)).filter((t) => !NAME_STOP.has(t));
  const key = tokens.join(' ');
  return key.length >= 3 ? key : null;
}

/**
 * Ключ дубля строки Базы: название + адрес, как просил Дима.
 * null, если хотя бы одной половины нет — по половине не склеиваем.
 */
export function dupKey(name, address) {
  const n = nameKey(name), a = addrKey(address);
  return n && a ? `${n}@${a}` : null;
}
