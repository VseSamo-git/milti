/**
 * Гео-фильтр «это Москва?».
 *
 * Store-locator'ы сетей отдают точки по всей России, а Диме нужна только
 * Москва. Явного поля «город» почти ни у кого нет — фильтруем по координатам
 * плюс денилист подмосковных городов.
 *
 * Почему одного bbox мало: Красногорск (55.77, 37.24) и Мытищи (55.9, 37.7)
 * попадают внутрь прямоугольника Москвы, но это область. Их ловим по адресу.
 * Почему одного адреса мало: у части точек в адресе нет города вовсе
 * («Верейская Плаза»), но по координатам это Москва. Нужны оба признака.
 *
 * Троицк НЕ исключаем: это ТиНАО, формально Москва.
 */

// Границы Москвы с запасом: ТиНАО на юго-западе и Зеленоград на северо-западе.
export const MOSCOW_BBOX = { south: 55.30, west: 36.80, north: 56.05, east: 37.98 };

// Города и признаки Московской области, попадающие внутрь bbox Москвы.
// Проверено рецептами разведки: Красногорск (Bodro, Prime), Мытищи (Караваевы),
// аэропорты Домодедово/Шереметьево (Му-Му).
const MO_MARKERS = [
  /мытищи/i, /красногорск/i, /химки/i, /одинцов/i, /люберц/i, /котельник/i,
  /реутов/i, /балаших/i, /видное/i, /домодедов/i, /шереметьев/i, /зеленоград/i,
  /московская\s+обл/i, /моск\.?\s*обл/i, /\bмо\b/i,
];

export function inMoscowBbox(lat, lon) {
  return (
    typeof lat === 'number' && typeof lon === 'number' &&
    lat >= MOSCOW_BBOX.south && lat <= MOSCOW_BBOX.north &&
    lon >= MOSCOW_BBOX.west && lon <= MOSCOW_BBOX.east
  );
}

/** Похоже ли по тексту адреса, что это область, а не Москва. */
export function looksOutsideMoscow(text) {
  if (!text) return false;
  return MO_MARKERS.some((re) => re.test(text));
}

/**
 * Точка в Москве: и координаты внутри границ, и адрес не выдаёт область.
 * Зеленоград исключён намеренно — это отдельный город-эксклав, для «минуты
 * ходьбы от офиса в центре» нерелевантен; при необходимости убрать из MO_MARKERS.
 */
export function isMoscow(lat, lon, address) {
  return inMoscowBbox(lat, lon) && !looksOutsideMoscow(address);
}
